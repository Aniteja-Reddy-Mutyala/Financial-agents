"""An open-weight LLM judge, via Groq's API, that reads the actual
generated answer and gives a real semantic-correctness verdict — unlike
run_eval.py's scorer, which only checks structural properties (intent
label, citation prefix, keyword presence) and never reads the answer text
for meaning.

Needs the `groq` package (`pip install groq`, not in the main project's
requirements.txt — this is an optional eval-only extra) and a Groq API
key: set the GROQ_API_KEY environment variable (console.groq.com).
Groq's free tier serves open-weight models (Llama 3.x and others) fast,
without requiring prepaid credits — the thing that blocked the earlier
Hugging Face Inference API attempt (see git history: that route is still
in place as reference but unused).

This judges answers already generated by run_eval.py — it does NOT call
the compliance agent again, so running it costs zero additional Bedrock
calls.
"""
import json
import os

DEFAULT_MODEL = "openai/gpt-oss-20b"

JUDGE_SYSTEM_PROMPT = (
    "You are an impartial evaluator grading a compliance assistant's answer. "
    "You will be given the user's question, the answer the assistant generated, "
    "and some ground-truth hints about what a correct answer should cover. "
    "Judge whether the answer is substantively correct and actually addresses "
    "the question — not just whether it name-drops the right section number. "
    "Respond with ONLY a JSON object, no other text, in this exact shape: "
    '{"correct": true or false, "reasoning": "one short sentence"}'
)


class GroqJudgeUnavailable(Exception):
    pass


class GroqJudge:
    def __init__(self, model_id=DEFAULT_MODEL, api_key=None):
        self.model_id = model_id
        self.api_key = api_key or os.environ.get("GROQ_API_KEY")
        if not self.api_key:
            raise GroqJudgeUnavailable(
                "No Groq API key found — set the GROQ_API_KEY environment variable."
            )
        self._client = None

    @property
    def client(self):
        if self._client is None:
            from groq import Groq  # lazy import

            self._client = Groq(api_key=self.api_key)
        return self._client

    def judge(self, query, answer, expected_citation_prefix, expected_keywords):
        user_prompt = (
            f"Question: {query}\n\n"
            f"Assistant's answer: {answer}\n\n"
            f"Ground-truth hints: the answer should cite a regulation starting "
            f"with \"{expected_citation_prefix}\", and ideally touches on one of: "
            f"{', '.join(expected_keywords)}.\n\n"
            "Is the answer substantively correct and genuinely responsive to the "
            "question? Respond with ONLY the JSON object described."
        )
        try:
            response = self.client.chat.completions.create(
                model=self.model_id,
                messages=[
                    {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
                # gpt-oss is a reasoning model — most of its token budget
                # goes to internal reasoning tokens before the visible JSON
                # (measured: up to 271 of 310 completion tokens on a single
                # case), so max_tokens needs real headroom above what the
                # final JSON alone would need, or responses come back empty
                # having hit the ceiling mid-reasoning.
                max_tokens=800,
                temperature=0.0,
            )
            content = response.choices[0].message.content.strip()
        except Exception as exc:  # noqa: BLE001 — want to degrade gracefully either way
            raise GroqJudgeUnavailable(str(exc)) from exc

        return self._parse_verdict(content)

    @staticmethod
    def _parse_verdict(content):
        # Models sometimes wrap JSON in markdown fences or add stray text —
        # extract the first {...} block rather than assuming a clean response.
        start = content.find("{")
        end = content.rfind("}")
        if start == -1 or end == -1 or end < start:
            return {"correct": None, "reasoning": f"unparseable judge output: {content[:200]!r}"}
        try:
            parsed = json.loads(content[start : end + 1])
            return {"correct": bool(parsed.get("correct")), "reasoning": parsed.get("reasoning", "")}
        except json.JSONDecodeError:
            return {"correct": None, "reasoning": f"unparseable judge output: {content[:200]!r}"}


if __name__ == "__main__":
    judge = GroqJudge()
    verdict = judge.judge(
        query="do we need to file a SAR for this wire transfer?",
        answer="Yes, under 31 CFR 1020.320, a bank must file a Suspicious Activity Report "
        "if it knows, suspects, or has reason to suspect a transaction is suspicious.",
        expected_citation_prefix="31 CFR",
        expected_keywords=["suspicious activity report", "sar"],
    )
    print(verdict)
