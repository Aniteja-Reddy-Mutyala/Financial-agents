"""An LLM judge that reads the actual generated answer and gives a real
semantic-correctness verdict — unlike run_eval.py's scorer, which only
checks structural properties (intent label, citation prefix, keyword
presence) and never reads the answer text for meaning.

Two interchangeable judge providers, same shared prompt (never edit
JUDGE_SYSTEM_PROMPT/_build_user_prompt for just one):

- **GroqJudge** (default) — an open-weight model via Groq's API. Needs
  the `groq` package (`pip install groq`, not in requirements.txt — an
  optional eval-only extra) and GROQ_API_KEY (console.groq.com). Groq's
  free tier serves this fast with no prepaid credits, but has a real
  daily token quota per model that a large judge run can exhaust (see
  run-evaluation-suite skill) — the cross-model workaround already
  documented there is passing `--model` on the CLI.
- **BedrockJudge** — judges via Amazon Bedrock instead, to work around
  Groq's daily quota entirely (a different, billed resource with its own
  limits, not Groq's). Deliberately defaults to a **different model
  family than BedrockSummarizer's Nova Micro** (`DEFAULT_BEDROCK_MODEL`)
  — using the same model to both generate and judge an answer risks the
  model being lenient on its own mistakes (self-evaluation bias), which
  is exactly the independence an external judge is for. Every call is a
  real, billed Bedrock call — see bedrock-llm-integration skill's cost
  awareness notes before running a large judge set this way.

This judges answers already generated by run_eval.py — it does NOT call
the compliance agent again, so running it costs zero additional
retrieval/generation calls either way.
"""
import json
import os

DEFAULT_MODEL = "openai/gpt-oss-20b"
DEFAULT_BEDROCK_MODEL = "amazon.nova-lite-v1:0"
# Claude models were tried first for maximum independence from
# BedrockSummarizer's Nova Micro (different provider entirely), but this
# account's Bedrock access to them returns AccessDeniedException /
# INVALID_PAYMENT_INSTRUMENT (an AWS Marketplace subscription issue, not a
# code bug) — not usable here. Nova Lite is a different model *tier* than
# Nova Micro at least, which is weaker separation than a different
# provider would give, but it's the most independent option this account
# can actually call. If Claude access gets fixed on the AWS side, switch
# back via --model.
DEFAULT_BEDROCK_REGION = os.environ.get("AWS_REGION", "us-east-1")

JUDGE_SYSTEM_PROMPT = (
    "You are an impartial evaluator grading a compliance assistant's answer. "
    "You will be given the user's question, the answer the assistant generated, "
    "and some ground-truth hints about what a correct answer should cover. "
    "Judge whether the answer is substantively correct and actually addresses "
    "the question — not just whether it name-drops the right section number. "
    "Respond with ONLY a JSON object, no other text, in this exact shape: "
    '{"correct": true or false, "reasoning": "one short sentence"}'
)


def _build_user_prompt(query, answer, expected_citation_prefix, expected_keywords):
    return (
        f"Question: {query}\n\n"
        f"Assistant's answer: {answer}\n\n"
        f"Ground-truth hints: the answer should cite a regulation starting "
        f"with \"{expected_citation_prefix}\", and ideally touches on one of: "
        f"{', '.join(expected_keywords)}.\n\n"
        "Is the answer substantively correct and genuinely responsive to the "
        "question? Respond with ONLY the JSON object described."
    )


def _parse_verdict(content):
    # Models sometimes wrap JSON in markdown fences or add stray text —
    # extract the first {...} block rather than assuming a clean response.
    start = content.find("{")
    end = content.rfind("}")
    if start == -1 or end == -1 or end < start:
        return {"correct": None, "reasoning": f"unparseable judge output: {content[:200]!r}"}
    try:
        parsed = json.loads(content[start : end + 1])
        return {"correct": bool(parsed.get("correct")), "reasoning": parsed.get("reasoning", "")}
    except json.JSONDecodeError:
        return {"correct": None, "reasoning": f"unparseable judge output: {content[:200]!r}"}


class GroqJudgeUnavailable(Exception):
    pass


class GroqJudge:
    def __init__(self, model_id=DEFAULT_MODEL, api_key=None):
        self.model_id = model_id
        self.api_key = api_key or os.environ.get("GROQ_API_KEY")
        if not self.api_key:
            raise GroqJudgeUnavailable(
                "No Groq API key found — set the GROQ_API_KEY environment variable."
            )
        self._client = None

    @property
    def client(self):
        if self._client is None:
            from groq import Groq  # lazy import

            self._client = Groq(api_key=self.api_key)
        return self._client

    def judge(self, query, answer, expected_citation_prefix, expected_keywords):
        user_prompt = _build_user_prompt(query, answer, expected_citation_prefix, expected_keywords)
        try:
            response = self.client.chat.completions.create(
                model=self.model_id,
                messages=[
                    {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
                # gpt-oss is a reasoning model — most of its token budget
                # goes to internal reasoning tokens before the visible JSON
                # (measured: up to 271 of 310 completion tokens on a single
                # case), so max_tokens needs real headroom above what the
                # final JSON alone would need, or responses come back empty
                # having hit the ceiling mid-reasoning.
                max_tokens=800,
                temperature=0.0,
            )
            content = response.choices[0].message.content.strip()
        except Exception as exc:  # noqa: BLE001 — want to degrade gracefully either way
            raise GroqJudgeUnavailable(str(exc)) from exc

        return _parse_verdict(content)


class BedrockJudgeUnavailable(Exception):
    pass


class BedrockJudge:
    """Judges via Amazon Bedrock instead of Groq — see module docstring
    for why the default model deliberately differs from
    BedrockSummarizer's Nova Micro."""

    def __init__(self, model_id=DEFAULT_BEDROCK_MODEL, region=DEFAULT_BEDROCK_REGION):
        self.model_id = model_id
        self.region = region
        self._llm = None

    @property
    def llm(self):
        if self._llm is None:
            from langchain_aws import ChatBedrockConverse  # lazy import

            self._llm = ChatBedrockConverse(
                model=self.model_id, region_name=self.region, temperature=0.0, max_tokens=800
            )
        return self._llm

    def judge(self, query, answer, expected_citation_prefix, expected_keywords):
        from langchain_core.messages import HumanMessage, SystemMessage  # lazy import

        user_prompt = _build_user_prompt(query, answer, expected_citation_prefix, expected_keywords)
        try:
            response = self.llm.invoke(
                [SystemMessage(content=JUDGE_SYSTEM_PROMPT), HumanMessage(content=user_prompt)]
            )
            content = response.content.strip()
        except Exception as exc:  # noqa: BLE001 — want to degrade gracefully either way
            raise BedrockJudgeUnavailable(str(exc)) from exc

        return _parse_verdict(content)


if __name__ == "__main__":
    for judge in (GroqJudge(), BedrockJudge()):
        verdict = judge.judge(
            query="do we need to file a SAR for this wire transfer?",
            answer="Yes, under 31 CFR 1020.320, a bank must file a Suspicious Activity Report "
            "if it knows, suspects, or has reason to suspect a transaction is suspicious.",
            expected_citation_prefix="31 CFR",
            expected_keywords=["suspicious activity report", "sar"],
        )
        print(judge.__class__.__name__, verdict)
